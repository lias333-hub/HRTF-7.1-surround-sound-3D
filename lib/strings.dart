  static const List<LangInfo> languages = [
    LangInfo('ar', 'العربية'),
    LangInfo('en', 'English'),
    LangInfo('fr', 'Français'),
    LangInfo('es', 'Español'),
    LangInfo('tr', 'Türkçe'),
  ];

  /// What the user picked: 'system' or a language code.
  static String pref = 'system';

  /// The language actually in use (always a supported code).
  static String lang = 'en';

  static bool get rtl => lang == 'ar';

  static bool isSupported(String code) => languages.any((l) => l.code == code);

  /// Sets [pref] and resolves [lang]; unknown values fall back to the system language, then English.
  static void setPref(String p, String systemCode) {
    pref = (p == 'system' || isSupported(p)) ? p : 'system';
    if (pref == 'system') {
      lang = isSupported(systemCode) ? systemCode : 'en';
    } else {
      lang = pref;
    }
  }

  static String nameOf(String code) =>
      languages.firstWhere((l) => l.code == code, orElse: () => languages[1]).name;

  static String t(String key) => _m[lang]?[key] ?? _m['en']![key] ?? key;

  /// Like [t], replacing {placeholders}.
  static String f(String key, Map<String, String> args) {
    var s = t(key);
    args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }

  /// Display name of a profile key (built-ins are translated, user names are shown as typed).
  static String profileName(String key) =>
      key.startsWith('builtin:') ? t(key.substring(8)) : key;

  /// For tests: every language's key set.
  static Map<String, Map<String, String>> get all => _m;

