#!/usr/bin/env python3
"""Generates native/cpp/test/golden.h: reference vectors for the C++ core, computed with numpy/scipy in double
precision. Run it only when the test cases change; the result is committed. Usage: python3 tools/gen_golden.py"""
import numpy as np
from scipy import signal

N = 480
rng = np.random.default_rng(1234)
x = rng.uniform(-1, 1, N).astype(np.float32)

# 1) six-pole Butterworth low-pass as three biquads (scipy "sos": b0 b1 b2 a0 a1 a2)
sos = signal.butter(6, 0.2, output="sos")
sos5 = np.array([[r[0], r[1], r[2], r[4], r[5]] for r in sos], dtype=np.float32)  # b0 b1 b2 a1 a2 (a0 == 1)
# The reference uses the same float32-rounded coefficients as the C++ kernel, so the test checks the kernel's
# arithmetic and not the rounding of the coefficients.
sos_ref = np.array([[r[0], r[1], r[2], 1.0, r[3], r[4]] for r in sos5.astype(np.float64)])
y_sos = signal.sosfilt(sos_ref, x.astype(np.float64))

# 2) FIR, 129 taps (odd count on purpose: exercises the non-multiple-of-4 paths), zero history
taps = 129
h = signal.firwin(taps, 0.3).astype(np.float32)
y_fir = np.convolve(x.astype(np.float64), h.astype(np.float64))[:N]

# 3) RBJ peaking coefficients, computed independently here with the textbook formula
def rbj(fs, f0, gdb, q):
    A = 10 ** (gdb / 40)
    w0 = 2 * np.pi * f0 / fs
    al = np.sin(w0) / (2 * q)
    b0, b1, b2 = 1 + al * A, -2 * np.cos(w0), 1 - al * A
    a0, a1, a2 = 1 + al / A, -2 * np.cos(w0), 1 - al / A
    return np.array([b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0])

cases = [(48000, 1000, 6.0, 1.4), (48000, 31.25, -6.0, 1.4), (44100, 16000, 3.0, 0.7), (48000, 125, 12.0, 4.3)]
peak = np.array([rbj(*c) for c in cases], dtype=np.float32)

def arr(name, a):
    flat = np.asarray(a).ravel()
    body = ",".join(repr(float(v)) if abs(v) < 1e-30 else "%.9g" % v for v in flat)
    return "static const float %s[%d] = {%s};\n" % (name, flat.size, body)

def darr(name, a):
    flat = np.asarray(a).ravel()
    body = ",".join("%.17g" % v for v in flat)
    return "static const double %s[%d] = {%s};\n" % (name, flat.size, body)

out = ["// GENERATED by tools/gen_golden.py - do not edit by hand.\n#pragma once\n",
       "static const int kGoldN = %d;\nstatic const int kGoldSections = %d;\nstatic const int kGoldTaps = %d;\nstatic const int kGoldPeakCases = %d;\n" % (N, len(sos5), taps, len(cases)),
       arr("kGoldX", x), arr("kGoldSos", sos5), darr("kGoldSosY", y_sos),
       arr("kGoldH", h), darr("kGoldFirY", y_fir),
       arr("kGoldPeakIn", np.array(cases, dtype=np.float32)), darr("kGoldPeakOut", peak.astype(np.float64))]
open("native/cpp/test/golden.h", "w").write("".join(out))
print("golden.h written; sos sections:", len(sos5), "max |y_sos|:", float(np.abs(y_sos).max()))
